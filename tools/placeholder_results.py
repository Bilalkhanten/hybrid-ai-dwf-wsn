"""Fill results_template.json with PLACEHOLDER numbers so that make_figures.py can be exercised in CI.

    python tools/placeholder_results.py results_template.json placeholder.json

These numbers are made up (a ramp of values with a +-5 interval). They only prove that the plotting code runs.
They are never a result and the figures drawn from them must not be published or used in the manuscript.
Nulls that are a whole table entry (the template's "n/a" cells) are kept as they are.
"""
import json
import sys


def fill(entry, i):
    """[null, null] -> [mean, SD]; [null, null, null] -> [mean, CI low, CI high]; i varies the mean per row."""
    mean = 60.0 + 5.0 * i
    if len(entry) == 2:
        return [mean, 2.0]
    if len(entry) == 3:
        return [mean, mean - 5.0, mean + 5.0]
    raise SystemExit(f"unexpected entry length {len(entry)}: {entry}")


def main(src, dst):
    template = json.load(open(src))
    for name, table in template.items():
        if name.startswith("_"):
            continue
        for key, rows in table.items():
            if key.startswith("_") or not isinstance(rows, list):
                continue
            for i, row in enumerate(rows):
                if isinstance(row, list) and any(v is None for v in row):
                    rows[i] = fill(row, i)
    template["_note"] = "PLACEHOLDER numbers generated by tools/placeholder_results.py; not results"
    left = json.dumps(template).count("null")
    json.dump(template, open(dst, "w"), indent=1)
    print(f"wrote {dst} ({left} 'n/a' cells left as null)")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
